let activeCategory = "all";
function filterArticles() {
  const query = document.getElementById("searchInput").value.trim().toLowerCase();
  let visible = 0;
  document.querySelectorAll(".article-card").forEach(card => {
    const categoryMatch = activeCategory === "all" || card.dataset.category === activeCategory;
    const searchMatch = !query || (card.innerText + " " + card.dataset.search).toLowerCase().includes(query);
    card.hidden = !(categoryMatch && searchMatch);
    if (!card.hidden) visible++;
  });
  document.getElementById("emptyState").hidden = visible > 0;
  document.getElementById("searchCount").textContent = query ? `${visible} / ${document.querySelectorAll(".article-card").length}` : "";
}
document.querySelectorAll(".category").forEach(btn => btn.addEventListener("click", () => {
  activeCategory = btn.dataset.category;
  document.querySelectorAll(".category").forEach(b => b.classList.toggle("active", b === btn));
  filterArticles();
}));
