function openArticleDetail(card, articleData) {
  const title = articleData?.title || card.querySelector("h3")?.textContent || "";
  const lead = articleData?.text || card.querySelector("p")?.textContent || "";
  const content = articleData?.content || lead;
  const category = articleData?.category || card.querySelector(".article-tag")?.textContent || "MAQOLA";
  const categoryMap = { "Tadqiqotlar": "research", "Biotexnologiya": "biotech", "Tibbiyot": "medicine", "Biotibbiyot": "biomed" };
  const categoryClass = categoryMap[category] || card.dataset.category || "research";
  const detailImage = document.getElementById("detailImage");
  const imageUrl = articleData?.image || siteMedia[`cover-${categoryClass}`];
  const articleCover = card.querySelector(".article-image");
  detailImage.className = `detail-image ${articleCover?.className.split(" ").filter(name => name.startsWith("cover-")).join(" ") || ""}`;
  detailImage.style.backgroundImage = articleCover ? getComputedStyle(articleCover).backgroundImage : "";
  detailImage.innerHTML = imageUrl ? `<img src="${escapeHtml(imageUrl)}" alt="${escapeHtml(title)}">` : "";
  document.getElementById("detailMeta").textContent = `${category.toUpperCase()} • ILMIY MAQOLA`;
  document.getElementById("detailTitle").textContent = title;
  document.getElementById("detailLead").textContent = lead;
  document.getElementById("detailBody").innerHTML = content.split(/\n+/).filter(Boolean).map(paragraph => `<p>${paragraph.replace(/</g,"&lt;").replace(/>/g,"&gt;")}</p>`).join("");
  articleDetail.showModal();
}

document.addEventListener("click", event => {
  const link = event.target.closest(".article-card .article-image, .article-card .read-link");
  if (!link) return;
  event.preventDefault();
  const card = link.closest(".article-card");
  const hrefId = link.getAttribute("href");
  const articleId = hrefId ? hrefId.replace("#article-", "") : "";
  const adminArticle = publishedArticles.find(article => String(article.id) === articleId);
  openArticleDetail(card, adminArticle);
});
