let publishedArticles = [];
let siteMedia = {};
function escapeHtml(value) {
  const element = document.createElement("div");
  element.textContent = value || "";
  return element.innerHTML;
}

function renderAdminArticles() {
  const grid = document.getElementById("articleGrid");
  grid.innerHTML = publishedArticles.map((article, index) => {
    const categoryMap = { "Tadqiqotlar": "research", "Biotexnologiya": "biotech", "Tibbiyot": "medicine", "Biotibbiyot": "biomed" };
    const categoryClass = categoryMap[article.category] || "research";
    const readTime = Math.max(2, Math.ceil((article.content || article.text).trim().split(/\s+/).length / 200));
    const coverImage = article.image || siteMedia[`cover-${categoryClass}`];
    const image = coverImage
      ? `<img src="${escapeHtml(coverImage)}" alt="${escapeHtml(article.title)}">`
      : "";
    return `
      <article class="article-card" data-category="${categoryClass}" data-search="${escapeHtml(`${article.category} ${article.title} ${article.text}`)}">
        <a class="article-image custom-article-image${image ? "" : ` cover-${categoryClass}`}" href="#article-${escapeHtml(article.id)}" aria-label="${escapeHtml(article.title)}">
          ${image}<span class="article-tag">${escapeHtml(article.category.toUpperCase())}</span><span class="image-index">${String(index + 1).padStart(2, "0")} / ${String(publishedArticles.length).padStart(2, "0")}</span>
        </a>
        <div class="article-body">
          <div class="article-meta"><span>MAQOLA</span><span>•</span><span>${readTime} MIN</span></div>
          <h3>${escapeHtml(article.title)}</h3>
          <p>${escapeHtml(article.text)}</p>
          <a class="read-link" href="#article-${escapeHtml(article.id)}">Batafsil o‘qish <span>→</span></a>
        </div>
      </article>`;
  }).join("");
}

fetch("/api/articles")
  .then(response => {
    if (!response.ok) throw new Error("Maqolalarni yuklab bo‘lmadi.");
    return response.json();
  })
  .then(data => {
    publishedArticles = data;
    renderAdminArticles();
    filterArticles();
  })
  .catch(error => {
    document.getElementById("emptyState").hidden = false;
    document.getElementById("emptyState").textContent = error.message;
  });

fetch("/api/site-media")
  .then(response => {
    if (!response.ok) throw new Error("Sayt rasmlarini yuklab bo‘lmadi.");
    return response.json();
  })
  .then(media => {
    siteMedia = media;
    if (siteMedia.hero) {
      const heroImage = document.querySelector(".hero-image");
      heroImage.classList.add("uploaded-media");
      heroImage.style.backgroundImage =
        `linear-gradient(110deg, #0e2c4766, #0e2c4700 80%), url("${siteMedia.hero}")`;
    }
    if (siteMedia.research) {
      const researchSection = document.getElementById("research");
      researchSection.style.backgroundImage =
        `linear-gradient(115deg, #102b46d9, #173c58b3), url("${siteMedia.research}")`;
      researchSection.style.backgroundSize = "auto, contain";
      researchSection.style.backgroundPosition = "center";
      researchSection.style.backgroundRepeat = "no-repeat";
    }
    renderAdminArticles();
    filterArticles();
  })
  .catch(error => console.error("Sayt rasmlarini qo‘llashda xatolik:", error));

